#!/usr/bin/env python3
"""ref_index.py -- keep a compact lookup index at the top of the big reference files.

    python3 scripts/ref_index.py            # rewrite the index blocks in place
    python3 scripts/ref_index.py --check    # exit 1 if any index block is missing or stale
    python3 scripts/ref_index.py --selftest # offline

Files: references/books/GLOSSARY.md, references/books/hash-snargs/MAP.md, references/books/thaler/MAP.md.
Agents and skills read these files by lookup, not whole: the index (between the INDEX markers, right after the
title) gives every section's line range, the terms of each glossary section and the line of each map entry, so
a reader runs `sed -n 'A,Bp' FILE` or `grep -n -i '<term or label>' FILE` and reads a few lines. Line numbers
are of the file *with* the index in place. scripts/check_book_refs.py runs the --check part on every scan.
"""
from __future__ import annotations

import os
import re
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = ["references/books/GLOSSARY.md", "references/books/hash-snargs/MAP.md", "references/books/thaler/MAP.md"]
BEGIN = "<!-- INDEX:BEGIN generated by scripts/ref_index.py; do not edit by hand -->"
END = "<!-- INDEX:END -->"


def strip_index(text: str) -> str:
    a, b = text.find(BEGIN), text.find(END)
    if a < 0 or b < a:
        return text
    tail = text[b + len(END):]
    return text[:a] + (tail[1:] if tail.startswith("\n") else tail)


def _clean(s: str) -> str:
    s = re.sub(r"\*\*|`", "", s).strip()
    return s.rstrip(".").strip()


def build(rel: str, lines: list[str], offset: int) -> list[str]:
    """Index lines for a file whose body (without index) is `lines`; body line i lands at i + 1 + offset."""
    ln = lambda i: i + 1 + offset
    heads = [(i, len(m.group(1)), m.group(2).strip()) for i, l in enumerate(lines)
             if (m := re.match(r"^(#{2,3}) (.+)$", l))]
    def end_of(k):
        lvl = heads[k][1]
        for j in range(k + 1, len(heads)):
            if heads[j][1] <= lvl:
                return heads[j][0] - 1
        return len(lines) - 1
    out = [BEGIN]
    is_gloss = rel.endswith("GLOSSARY.md")
    if is_gloss:
        out += [f"**Lookup index.** Do not read this file whole: `grep -n -i '<term>' {rel}` or "
                f"`sed -n 'A,Bp' {rel}` for one section.", "", "| lines | section | terms |", "|---|---|---|"]
        for k, (i, lvl, title) in enumerate(heads):
            terms = []
            sec = lines[i + 1:end_of(k) + 1]
            for n, l in enumerate(sec):
                m = re.match(r"^\| ([^|]+?) \|", l)
                header = n + 1 < len(sec) and sec[n + 1].startswith("|---")
                if m and not header and not set(m.group(1)) <= set("-: "):
                    terms.append(_clean(m.group(1)))
            out.append(f"| {ln(i)}–{ln(end_of(k))} | {title} | {', '.join(terms) or '(prose)'} |")
    else:
        out += [f"**Lookup index.** Do not read this file whole: `grep -n '<label>' {rel}` (a label such as "
                f"`lemma:mt-binding` or `§4.1`, or a skill name for the By-task rows) or `sed -n 'A,Bp' {rel}` for one entry or section.", ""]
        for k, (i, lvl, title) in enumerate(heads):
            entries = []
            for j in range(i + 1, end_of(k) + 1):
                if lvl == 2 and any(h[0] == j for h in heads):
                    break
                m = re.match(r"^- \*\*(.+?)\*\*", lines[j])
                if m:
                    entries.append(f"{_clean(m.group(1))} {ln(j)}")
            body = f": {'; '.join(entries)}" if entries else ""
            out.append(f"- {ln(i)}–{ln(end_of(k))} {title}{body}")
    out.append(END)
    return out


def render(rel: str, text: str) -> str:
    body = strip_index(text)
    lines = body.split("\n")
    head = 1  # the index goes right after the H1 title line
    n_idx = len(build(rel, lines[head:], 0))  # the index length does not depend on the numbers it prints
    idx = build(rel, lines[head:], head + n_idx)  # body line j (after the title) lands at head + n_idx + j + 1
    return "\n".join(lines[:head] + idx + lines[head:])


def run(check: bool, root: str = ROOT, out=sys.stdout) -> int:
    bad = 0
    for rel in FILES:
        p = os.path.join(root, rel)
        text = open(p, encoding="utf-8").read()
        new = render(rel, text)
        if new != text:
            if check:
                print(f"FAIL {rel}: lookup index missing or stale; run python3 scripts/ref_index.py", file=out)
                bad += 1
            else:
                open(p, "w", encoding="utf-8").write(new)
                print(f"wrote index in {rel}", file=out)
    return 1 if bad else 0


def selftest() -> int:
    g = "# G\n\nintro\n\n## A\n\n| term | def |\n|---|---|\n| **proof** | x |\n| ROM | y |\n\n## B\n\nprose only\n"
    r = render("references/books/GLOSSARY.md", g)
    lines = r.split("\n")
    assert lines[1] == BEGIN and render("references/books/GLOSSARY.md", r) == r, "idempotent"
    row = next(l for l in lines if l.startswith("| ") and "| A |" in l)
    a, b = map(int, re.match(r"\| (\d+)–(\d+)", row).groups())
    assert lines[a - 1] == "## A" and lines[b - 1] == "", (a, b)
    assert "proof, ROM" in row
    m = "# M\n\nx\n\n## Chapters\n\n### Part: P\n\n- **The ROM.** text\n  more\n\n## By task\n\n| t | o |\n"
    r = render("references/books/hash-snargs/MAP.md", m)
    lines = r.split("\n")
    ent = next(l for l in lines if "The ROM" in l and l.startswith("- "))
    n = int(re.search(r"The ROM (\d+)", ent).group(1))
    assert lines[n - 1].startswith("- **The ROM.**"), n
    assert strip_index(r) == m
    with tempfile.TemporaryDirectory() as tmp:
        for rel in FILES:
            os.makedirs(os.path.dirname(os.path.join(tmp, rel)), exist_ok=True)
            open(os.path.join(tmp, rel), "w").write(g if rel.endswith("GLOSSARY.md") else m)
        sink = open(os.devnull, "w")
        assert run(True, tmp, sink) == 1 and run(False, tmp, sink) == 0 and run(True, tmp, sink) == 0
    print("selftest: all checks passed")
    return 0


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if "--selftest" in argv:
        return selftest()
    return run("--check" in argv)


if __name__ == "__main__":
    sys.exit(main())
