#!/usr/bin/env python3
"""codex_export.py -- install the toolkit for OpenAI Codex (called by install.sh --codex).

    python3 scripts/codex_export.py --dest <project-dir> [--link]   # project install
    python3 scripts/codex_export.py --user [--link]                 # every project (~/.agents, ~/.codex)
    python3 scripts/codex_export.py --selftest                      # offline

What goes where (Codex docs: "Agent Skills" and "Subagents"):

  skills/<name>/          -> <dest>/.agents/skills/<name>/        copied (or symlinked with --link)
  commands/cra-<x>.md     -> <dest>/.agents/skills/cra-<x>/SKILL.md   Codex has no repo-shared slash
                             commands (custom prompts are deprecated), so each command becomes a skill,
                             invoked as $cra-<x> or by name
  agents/<name>.md        -> <dest>/.codex/agents/<name>.toml      custom subagent: name, description,
                             developer_instructions (the role prompt); the Claude-only `tools` and
                             `model` front-matter keys are dropped, so the agent inherits the session's

A project install also copies workflows/ to .cra/workflows/ and AGENTS.md (if absent), and writes
.cra/toolkit-path so /cra-init-style steps can find templates/ (this file holds a local path and
belongs to the user's project, never to this repository).
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

CODEX_NOTE = (
    "Running under Codex: \"the Agent tool\" or \"dispatch <agent>\" means spawning the custom "
    "subagent of that name (.codex/agents/<agent>.toml); if subagents are unavailable, read that "
    "file's developer_instructions and follow them yourself, one role at a time. Toolkit paths: "
    "skills/<name>/ is .agents/skills/<name>/, workflows/ is .cra/workflows/, and templates/ is "
    "under the toolkit directory named in .cra/toolkit-path."
)


def split_front_matter(text: str) -> tuple[dict[str, str], str]:
    """Return (front-matter dict of the simple `key: value` lines, body)."""
    m = re.match(r"---\n(.*?)\n---\n?", text, re.S)
    if not m:
        return {}, text
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.startswith((" ", "\t")):
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()
    return meta, text[m.end():]


def toml_str(s: str) -> str:
    """A TOML basic string (single line)."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def toml_multiline(s: str) -> str:
    """A TOML multi-line basic string; escapes backslashes and runs of quotes."""
    body = s.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    if body.endswith('"'):
        body = body[:-1] + '\\"'
    return '"""\n' + body + '"""'


def agent_toml(md: str) -> tuple[str, str]:
    meta, body = split_front_matter(md)
    name, desc = meta.get("name"), meta.get("description")
    if not name or not desc:
        raise ValueError("agent file needs name and description front matter")
    instr = CODEX_NOTE + "\n\n" + body.strip() + "\n"
    out = (f"# Generated by scripts/codex_export.py from agents/{name}.md -- edit the .md, not this file.\n"
           f"name = {toml_str(name)}\n"
           f"description = {toml_str(desc)}\n"
           f"developer_instructions = {toml_multiline(instr)}\n")
    return name, out


def command_skill(cmd_name: str, md: str) -> str:
    meta, body = split_front_matter(md)
    desc = meta.get("description", cmd_name)
    hint = meta.get("argument-hint", "").strip()
    args = f"the arguments the user gave after ${cmd_name}" + (f" (form: {hint})" if hint else "")
    body = body.strip().replace("$ARGUMENTS", f"<{args}>")
    head = (f"---\nname: {cmd_name}\n"
            f"description: {desc}. The zk-research-agents command /{cmd_name}; use when the user asks "
            f"for ${cmd_name} or /{cmd_name}.\n---\n")
    return (head + f"# {cmd_name}\n\n"
            f"Generated by scripts/codex_export.py from commands/{cmd_name}.md.\n\n"
            f"{CODEX_NOTE}\n\n{body}\n")


def put(src: str, dst: str, link: bool) -> None:
    if os.path.islink(dst) or os.path.isfile(dst):
        os.remove(dst)
    elif os.path.isdir(dst):
        shutil.rmtree(dst)
    if link:
        os.symlink(src, dst)
    elif os.path.isdir(src):
        shutil.copytree(src, dst)
    else:
        shutil.copy2(src, dst)


def write(path: str, text: str) -> None:
    if os.path.islink(path):
        os.remove(path)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def install(toolkit: str, dest: str, user: bool, link: bool) -> list[str]:
    skills_dir = os.path.join(dest, ".agents", "skills")
    agents_dir = os.path.join(dest, ".codex", "agents")
    os.makedirs(skills_dir, exist_ok=True)
    os.makedirs(agents_dir, exist_ok=True)
    done = []
    for name in sorted(os.listdir(os.path.join(toolkit, "skills"))):
        src = os.path.join(toolkit, "skills", name)
        if os.path.isfile(os.path.join(src, "SKILL.md")):
            put(src, os.path.join(skills_dir, name), link)
            done.append(f"skill {name}")
    for fn in sorted(os.listdir(os.path.join(toolkit, "commands"))):
        if fn.endswith(".md"):
            cmd = fn[:-3]
            with open(os.path.join(toolkit, "commands", fn), encoding="utf-8") as f:
                text = command_skill(cmd, f.read())
            d = os.path.join(skills_dir, cmd)
            if os.path.islink(d):
                os.remove(d)
            os.makedirs(d, exist_ok=True)
            write(os.path.join(d, "SKILL.md"), text)
            done.append(f"command {cmd}")
    for fn in sorted(os.listdir(os.path.join(toolkit, "agents"))):
        if fn.endswith(".md"):
            with open(os.path.join(toolkit, "agents", fn), encoding="utf-8") as f:
                name, text = agent_toml(f.read())
            write(os.path.join(agents_dir, f"{name}.toml"), text)
            done.append(f"agent {name}")
    if not user:
        cra = os.path.join(dest, ".cra")
        os.makedirs(cra, exist_ok=True)
        put(os.path.join(toolkit, "workflows"), os.path.join(cra, "workflows"), link)
        write(os.path.join(cra, "toolkit-path"), os.path.abspath(toolkit) + "\n")
        if not os.path.exists(os.path.join(dest, "AGENTS.md")):
            shutil.copy2(os.path.join(toolkit, "AGENTS.md"), os.path.join(dest, "AGENTS.md"))
    return done


def selftest() -> int:
    try:
        import tomllib  # Python >= 3.11
    except ImportError:
        tomllib = None
    tricky = 'body with "quotes", a \\ backslash, """ triple quotes and a final quote"'
    name, t = agent_toml(f"---\nname: x\ndescription: d \"q\"\ntools: Read\n---\n{tricky}\n")
    assert name == "x" and "tools" not in t
    if tomllib:
        doc = tomllib.loads(t)
        assert doc["name"] == "x" and doc["description"] == 'd "q"'
        assert doc["developer_instructions"].endswith(tricky + "\n"), doc["developer_instructions"][-80:]
    s = command_skill("cra-demo", "---\ndescription: Demo\nargument-hint: <a>\n---\nDo $ARGUMENTS now.\n")
    meta, body = split_front_matter(s)
    assert meta["name"] == "cra-demo" and "$ARGUMENTS" not in body and "(form: <a>)" in body
    with tempfile.TemporaryDirectory() as tmp:
        done = install(ROOT, tmp, user=False, link=False)
        n_skills = sum(d.startswith("skill ") for d in done)
        n_cmds = sum(d.startswith("command ") for d in done)
        n_agents = sum(d.startswith("agent ") for d in done)
        assert n_skills == len([d for d in os.listdir(os.path.join(ROOT, "skills"))
                                if os.path.isfile(os.path.join(ROOT, "skills", d, "SKILL.md"))])
        assert n_cmds == len([f for f in os.listdir(os.path.join(ROOT, "commands")) if f.endswith(".md")])
        assert n_agents == len([f for f in os.listdir(os.path.join(ROOT, "agents")) if f.endswith(".md")])
        for fn in os.listdir(os.path.join(tmp, ".codex", "agents")):
            with open(os.path.join(tmp, ".codex", "agents", fn), encoding="utf-8") as f:
                txt = f.read()
            if tomllib:
                doc = tomllib.loads(txt)
                assert {"name", "description", "developer_instructions"} <= doc.keys(), fn
                assert doc["name"] + ".toml" == fn
        for d in os.listdir(os.path.join(tmp, ".agents", "skills")):
            with open(os.path.join(tmp, ".agents", "skills", d, "SKILL.md"), encoding="utf-8") as f:
                meta, _ = split_front_matter(f.read())
            assert meta.get("name") == d and meta.get("description"), d
        assert os.path.isfile(os.path.join(tmp, ".cra", "workflows", "PHASES.md"))
        assert os.path.isfile(os.path.join(tmp, "AGENTS.md"))
        install(ROOT, tmp, user=False, link=True)  # re-install over a copy, as symlinks
        assert os.path.islink(os.path.join(tmp, ".agents", "skills", "falsify"))
    print(f"selftest: all checks passed ({n_skills} skills, {n_cmds} commands, {n_agents} agents"
          f"{'' if tomllib else '; TOML parse skipped, Python < 3.11'})")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dest", help="project directory")
    ap.add_argument("--user", action="store_true", help="install into ~/.agents and ~/.codex")
    ap.add_argument("--link", action="store_true", help="symlink skills and workflows instead of copying")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        return selftest()
    if a.user == bool(a.dest):
        ap.error("give exactly one of --dest DIR or --user")
    dest = os.path.expanduser("~") if a.user else a.dest
    done = install(ROOT, dest, a.user, a.link)
    kinds = {k: sum(d.startswith(k + " ") for d in done) for k in ("skill", "command", "agent")}
    print(f"Codex: {kinds['skill']} skills and {kinds['command']} commands in {dest}/.agents/skills, "
          f"{kinds['agent']} agents in {dest}/.codex/agents")
    return 0


if __name__ == "__main__":
    sys.exit(main())
